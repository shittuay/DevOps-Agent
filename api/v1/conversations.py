@api_v1_bp.route('/chat/stream', methods=['POST'])
@require_api_key(scope='write')
def api_v1_chat_stream():
    """
    Send a message and receive a streaming AI response via SSE.

    Requires: API key with 'write' scope

    Body:
        message (string, required): Message content
        conversation_id (string, optional): Existing conversation ID. Auto-creates if omitted.

    Response: Server-Sent Events stream
        {"type": "chunk", "content": "text"}
        {"type": "done", "conversation_id": "...", "credits_remaining": N, "model_info": {...}}
        {"type": "error", "content": "..."}
    """
    from models import (
        db, Conversation, ChatMessage, UsageLog,
        UserSubscription, UserPreferences
    )
    from services.model_router import resolve_model_with_preference
    from services.chat_service import stream_free_tier_chat, is_anthropic_error

    from services.input_sanitizer import sanitize_input, validate_message
    from src.agent.guardrails import screen_message

    user_id = g.api_user.id
    data = request.get_json() or {}
    message = sanitize_input((data.get('message') or '').strip())

    if not message:
        return jsonify({'error': 'Message is required'}), 400

    # Guardrail layer 1: check if user is blocked
    if g.api_user.is_guardrail_blocked():
        return jsonify({'error': 'Account temporarily restricted due to repeated policy violations.'}), 403

    # Guardrail layer 2: injection pattern check
    is_valid, validation_reason = validate_message(message)
    if not is_valid:
        g.api_user.record_guardrail_violation()
        from models import db
        db.session.commit()
        return jsonify({'error': validation_reason}), 400

    # Guardrail layer 3: Haiku harmlessness screen
    guardrail_result = screen_message(message)
    if guardrail_result.blocked:
        g.api_user.record_guardrail_violation()
        from models import db
        db.session.commit()
        return jsonify({'error': 'Message blocked by content policy. Repeated violations may result in account suspension.'}), 400

    # Subscription / credits
    subscription, err = _ensure_subscription(user_id)
    if err:
        return err

    subscription.repair_if_never_used()
    tier_name = subscription.tier.name if subscription.tier else 'free'
    if not subscription.has_credits():
        if tier_name == 'free':
            from services.chat_service import generate_upgrade_pitch as _gup
            pitch = _gup()
            def _pitch_stream():
                yield f"data: {json.dumps({'type': 'chunk', 'content': pitch})}\n\n"
                yield f"data: {json.dumps({'type': 'done', 'credits_remaining': 0, 'trial_ended': True})}\n\n"
            return current_app.response_class(
                _pitch_stream(),
                mimetype='text/event-stream',
                headers={'Cache-Control': 'no-cache', 'X-Accel-Buffering': 'no', 'Connection': 'keep-alive'},
            )
        return jsonify({'error': 'insufficient_credits', 'credits_remaining': 0}), 402

    prefs = UserPreferences.query.filter_by(user_id=user_id).first()
    preferred_provider = prefs.preferred_model_provider if prefs else None
    model_config = resolve_model_with_preference(tier_name, preferred_provider)

    # Conversation
    conversation_id = data.get('conversation_id')
    is_first_message = False

    if conversation_id:
        conversation = Conversation.query.filter_by(
            id=conversation_id, user_id=user_id
        ).first()
        if not conversation:
            return jsonify({'error': 'Conversation not found'}), 404
        conversation.updated_at = datetime.utcnow()
        if conversation.title == 'New Chat':
            is_first_message = True
    else:
        conversation_id = str(uuid.uuid4())
        is_first_message = True
        conversation = Conversation(
            id=conversation_id,
            user_id=user_id,
            title='New Chat'
        )
        db.session.add(conversation)

    # Query history BEFORE adding the new message to avoid autoflush bug
    conversation_history = _get_conversation_history(user_id, conversation_id)

    # Save user message
    user_msg = ChatMessage(
        user_id=user_id,
        conversation_id=conversation_id,
        role='user',
        content=message
    )
    db.session.add(user_msg)

    # Preferences
    preferences_context = prefs.get_context_for_prompt() if prefs else None
    sandbox_active = False
    if prefs and prefs.learning_mode:
        try:
            from app import LEARNING_MODE_CONTEXT, SANDBOX_MODE_ADDENDUM
            preferences_context = (preferences_context or '') + '\n\n' + LEARNING_MODE_CONTEXT
            if prefs.sandbox_mode:
                preferences_context += '\n' + SANDBOX_MODE_ADDENDUM
                sandbox_active = True
        except ImportError:
            pass

    # Build trial context for free-tier users
    trial_context = None
    if tier_name == 'free':
        credits_left = subscription.credits_remaining
        trial_context = (
            f"TRIAL CONTEXT: This user is on a free trial with {credits_left} credits remaining out of 20. "
            "They are experiencing the full DevOps agent with real tool execution. "
        )
        if credits_left <= 5:
            trial_context += (
                "Their credits are running low. Naturally weave in a brief mention that they can "
                "upgrade to the Starter plan ($29/month) for 500 credits/month to keep using these tools. "
                "Do NOT make this the focus -- still answer their question fully first."
            )

    # Capture closure vars
    uid = user_id
    cid = conversation_id
    is_first = is_first_message
    msg_text = message
    mc = model_config
    tc = trial_context
    sb = sandbox_active
    agent = current_app.config.get('DEVOPS_AGENT')
    app = current_app._get_current_object()

    db.session.commit()

    def generate():
        from services.model_router import ModelConfig
        groq_fallback_mc = ModelConfig(
            provider='groq', model='llama-3.3-70b-versatile',
            display_name='Llama 3.3 70B (Fallback)', supports_tools=False,
        )
        full_response = []
        actual_mc = mc

        try:
            if mc.provider not in ('anthropic', 'kimi'):
                stream_source = stream_free_tier_chat(msg_text, conversation_history, preferences_context)
            else:
                try:
                    _provider_arg = 'kimi' if mc.provider == 'kimi' else None
                    stream_source = agent.process_message_streaming(
                        user_message=msg_text,
                        conversation_history=conversation_history,
                        user_preferences_context=preferences_context,
                        user_id=uid,
                        model_override=mc.model,
                        trial_context=tc,
                        sandbox_mode=sb,
                        provider=_provider_arg
                    )
                    # Buffer initial chunks to detect agent-swallowed errors
                    initial_buf = []
                    for _c in stream_source:
                        initial_buf.append(_c)
                        combined = ''.join(initial_buf)
                        if is_anthropic_error(combined):
                            actual_mc = groq_fallback_mc
                            stream_source = stream_free_tier_chat(msg_text, conversation_history, preferences_context)
                            break
                        if len(combined) > 20 or not combined.startswith(('\u274c', 'Error', 'API', '{')):
                            for buf_chunk in initial_buf:
                                full_response.append(buf_chunk)
                                yield f"data: {json.dumps({'type': 'chunk', 'content': buf_chunk})}\n\n"
                            break
                    else:
                        combined = ''.join(initial_buf)
                        if is_anthropic_error(combined):
                            actual_mc = groq_fallback_mc
                            stream_source = stream_free_tier_chat(msg_text, conversation_history, preferences_context)
                        else:
                            for buf_chunk in initial_buf:
                                full_response.append(buf_chunk)
                                yield f"data: {json.dumps({'type': 'chunk', 'content': buf_chunk})}\n\n"
                            stream_source = iter([])
                except Exception:
                    actual_mc = groq_fallback_mc
                    stream_source = stream_free_tier_chat(msg_text, conversation_history, preferences_context)

            for chunk in stream_source:
                full_response.append(chunk)
                yield f"data: {json.dumps({'type': 'chunk', 'content': chunk})}\n\n"

            # Append fallback note if we switched providers
            if actual_mc.provider != mc.provider:
                _fn = "Claude" if mc.provider == 'anthropic' else "Kimi"
                note = f"\n\n---\n*Note: {_fn} is temporarily unavailable. This response was generated by Llama 3.3 (Groq) without tool execution.*"
                full_response.append(note)
                yield f"data: {json.dumps({'type': 'chunk', 'content': note})}\n\n"

            from services.chat_service import ensure_non_empty_response
            complete = ensure_non_empty_response(''.join(full_response))

            # Save to DB
            with app.app_context():
                assistant_msg = ChatMessage(
                    user_id=uid,
                    conversation_id=cid,
                    role='assistant',
                    content=complete
                )
                db.session.add(assistant_msg)

                usage_log = UsageLog(
                    user_id=uid,
                    conversation_id=cid,
                    action_type='agent_message',
                    credits_used=1,
                    success=True,
                    ai_model=actual_mc.model
                )
                db.session.add(usage_log)

                if is_first:
                    c = Conversation.query.filter_by(id=cid, user_id=uid).first()
                    if c:
                        title = msg_text.strip()
                        if len(title) > 50:
                            title = title[:47] + '...'
                        c.title = title

                # Deduct credit AFTER successful AI response
                fresh_sub = UserSubscription.query.filter_by(user_id=uid).first()
                if fresh_sub:
                    fresh_sub.use_credit(commit=False)

                db.session.commit()

                remaining = fresh_sub.credits_remaining if fresh_sub else 0

            yield f"data: {json.dumps({'type': 'done', 'conversation_id': cid, 'credits_remaining': remaining, 'model_info': {'provider': actual_mc.provider, 'model': actual_mc.model, 'display_name': actual_mc.display_name, 'supports_tools': actual_mc.supports_tools}})}\n\n"

        except Exception as e:
            logger.error(f"Stream error: {e}", exc_info=True)
            yield f"data: {json.dumps({'type': 'error', 'content': str(e)})}\n\n"

    return current_app.response_class(
        generate(),
        mimetype='text/event-stream',
        headers={
            'Cache-Control': 'no-cache',
            'X-Accel-Buffering': 'no',
            'Connection': 'keep-alive',
        }
    )
