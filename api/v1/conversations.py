def _ensure_subscription(user_id):
    """Ensure user has a subscription, creating free tier if needed. Returns (subscription, error_response)."""
    from models import db, UserSubscription, SubscriptionTier

    subscription = UserSubscription.query.filter_by(user_id=user_id).first()
    if not subscription:
        free_tier = SubscriptionTier.query.filter_by(name='free').first()
        if not free_tier:
            return None, (jsonify({'error': 'Subscription system not initialized'}), 500)
        from datetime import datetime
        from dateutil.relativedelta import relativedelta
        now = datetime.utcnow()
        subscription = UserSubscription(
            user_id=user_id,
            tier_id=free_tier.id,
            credits_remaining=free_tier.monthly_credits,
            current_period_start=now,
            current_period_end=now + relativedelta(months=1),
            last_reset_date=now,
        )
        db.session.add(subscription)
        db.session.commit()

    # Reset monthly credits for paid tiers only — free tier is a one-time trial
    tier_name = subscription.tier.name if subscription.tier else 'free'
    if tier_name != 'free' and subscription.should_reset_credits():
        subscription.reset_monthly_credits()

    return subscription, None


def _check_credits(subscription):
    """Check credits are available. Returns error_response or None. Does NOT deduct."""
    subscription.repair_if_never_used()
    if not subscription.has_credits():
        tier_name = subscription.tier.name if subscription.tier else 'free'
        if tier_name == 'free':
            from services.chat_service import generate_upgrade_pitch
            return jsonify({
                'response': generate_upgrade_pitch(),
                'credits_remaining': 0,
                'trial_ended': True,
            })
        return jsonify({
            'error': 'insufficient_credits',
            'message': 'You have no credits remaining',
            'credits_remaining': 0
        }), 402
    return None


def _get_conversation_history(user_id, conversation_id):
    """Load conversation history from DB."""
    from models import ChatMessage
    prior = ChatMessage.query.filter_by(
        user_id=user_id,
        conversation_id=conversation_id
    ).order_by(ChatMessage.timestamp).all()
    return [{'role': m.role, 'content': m.content} for m in prior]


def _process_message(agent, message, conversation_history, preferences_context, user_id, model_config, trial_context=None, sandbox_mode=False):
    """Process a message through the appropriate AI provider with failover."""
    from services.chat_service import process_free_tier_chat, is_anthropic_error

    if model_config.provider not in ('anthropic', 'kimi'):
        return process_free_tier_chat(message, conversation_history, preferences_context), model_config

    provider_arg = 'kimi' if model_config.provider == 'kimi' else None

    try:
        response = agent.process_message_isolated(
            user_message=message,
            conversation_history=conversation_history,
            user_preferences_context=preferences_context,
            user_id=user_id,
            model_override=model_config.model,
            trial_context=trial_context,
            sandbox_mode=sandbox_mode,
            provider=provider_arg
        )
    except Exception:
        response = None

    if response and not is_anthropic_error(response):
        return response, model_config

    # Fallback to Groq
    fallback_note = "Claude" if model_config.provider == 'anthropic' else "Kimi"
    fallback_response = process_free_tier_chat(message, conversation_history, preferences_context)
    fallback_response += f"\n\n---\n*Note: {fallback_note} is temporarily unavailable. This response was generated by Llama 3.3 (Groq) without tool execution.*"
    from services.model_router import ModelConfig
    fallback_config = ModelConfig(
        provider='groq',
        model='llama-3.3-70b-versatile',
        display_name='Llama 3.3 70B (Fallback)',
        supports_tools=False,
    )
    return fallback_response, fallback_config


@api_v1_bp.route('/conversations', methods=['GET'])
@require_api_key(scope='read')
def list_conversations():
    """List user's conversations."""
    from models import Conversation

    user_id = g.api_user.id
    limit = min(request.args.get('limit', 20, type=int), 100)
    offset = request.args.get('offset', 0, type=int)

    conversations = Conversation.query.filter_by(user_id=user_id)\
        .order_by(Conversation.updated_at.desc())\
        .limit(limit)\
        .offset(offset)\
        .all()

    total = Conversation.query.filter_by(user_id=user_id).count()

    return jsonify({
        'conversations': [c.to_dict() for c in conversations],
        'pagination': {
            'total': total,
            'limit': limit,
            'offset': offset,
            'has_more': offset + limit < total
        }
    })


@api_v1_bp.route('/conversations/<conversation_id>', methods=['GET'])
@require_api_key(scope='read')
def get_conversation(conversation_id):
    """Get a specific conversation with messages."""
    from models import Conversation, ChatMessage

    user_id = g.api_user.id
    include_messages = request.args.get('include_messages', 'true').lower() == 'true'
    message_limit = min(request.args.get('message_limit', 50, type=int), 200)

    conversation = Conversation.query.filter_by(
        id=conversation_id,
        user_id=user_id
    ).first()

    if not conversation:
        return jsonify({
            'error': 'Not found',
            'message': 'Conversation not found'
        }), 404

    result = conversation.to_dict()

    if include_messages:
        messages = ChatMessage.query.filter_by(
            conversation_id=conversation_id,
            user_id=user_id
        ).order_by(ChatMessage.timestamp.asc())\
         .limit(message_limit)\
         .all()

        result['messages'] = [m.to_dict() for m in messages]

    return jsonify(result)


@api_v1_bp.route('/conversations', methods=['POST'])
@require_api_key(scope='write')
def create_conversation():
    """Create a new conversation."""
    from models import db, Conversation

    user_id = g.api_user.id
    data = request.get_json() or {}

    conversation = Conversation(
        id=str(uuid.uuid4()),
        user_id=user_id,
        title=data.get('title', 'New Chat')
    )

    db.session.add(conversation)
    db.session.commit()

    return jsonify({
        'message': 'Conversation created',
        'conversation': conversation.to_dict()
    }), 201


@api_v1_bp.route('/conversations/<conversation_id>', methods=['DELETE'])
@require_api_key(scope='write')
def delete_conversation(conversation_id):
    """Delete a conversation."""
    from models import (db, Conversation, ChatMessage, UsageLog, LearningSession,
                         WorkflowExecution, ChatArtifact, ApprovalRequest)

    user_id = g.api_user.id

    conversation = Conversation.query.filter_by(
        id=conversation_id,
        user_id=user_id
    ).first()

    if not conversation:
        return jsonify({
            'error': 'Not found',
            'message': 'Conversation not found'
        }), 404

    # Delete every other row that FKs to this conversation — see app.py's
    # delete_conversation() for why leaving any of these breaks the delete below.
    # ChatArtifact.message_id also FKs to chat_messages.id with no cascade, so
    # it must be deleted BEFORE the ChatMessage delete below, not after.
    ChatArtifact.query.filter_by(
        conversation_id=conversation_id,
        user_id=user_id
    ).delete()
    UsageLog.query.filter_by(
        conversation_id=conversation_id,
        user_id=user_id
    ).delete()
    LearningSession.query.filter_by(
        conversation_id=conversation_id,
        user_id=user_id
    ).delete()
    WorkflowExecution.query.filter_by(
        conversation_id=conversation_id,
        user_id=user_id
    ).delete()
    ApprovalRequest.query.filter_by(
        conversation_id=conversation_id,
        requester_id=user_id
    ).delete()

    ChatMessage.query.filter_by(
        conversation_id=conversation_id,
        user_id=user_id
    ).delete()

    db.session.delete(conversation)
    db.session.commit()

    return jsonify({'message': 'Conversation deleted'})


@api_v1_bp.route('/conversations/<conversation_id>/messages', methods=['POST'])
@require_api_key(scope='write')
def send_message(conversation_id):
    """
    Send a message to a conversation and get AI response.

    Requires: API key with 'write' scope

    Body:
        content (string, required): Message content
    """
    from models import db, Conversation, ChatMessage, UsageLog, UserPreferences
    from services.model_router import resolve_model_with_preference

    from models import db
    from services.input_sanitizer import sanitize_input, validate_message
    from src.agent.guardrails import screen_message

    user_id = g.api_user.id
    data = request.get_json() or {}

    if not data.get('content'):
        return jsonify({
            'error': 'Bad request',
            'message': 'Message content is required'
        }), 400

    content = sanitize_input(data['content'])
    if not content:
        return jsonify({
            'error': 'Bad request',
            'message': 'Message content is required'
        }), 400

    # Guardrail layer 1: check if user is blocked
    if g.api_user.is_guardrail_blocked():
        return jsonify({'error': 'Account temporarily restricted due to repeated policy violations.'}), 403

    # Guardrail layer 2: injection pattern check
    is_valid, validation_reason = validate_message(content)
    if not is_valid:
        g.api_user.record_guardrail_violation()
        db.session.commit()
        return jsonify({'error': validation_reason}), 400

    # Guardrail layer 3: Haiku harmlessness screen
    guardrail_result = screen_message(content)
    if guardrail_result.blocked:
        g.api_user.record_guardrail_violation()
        db.session.commit()
        return jsonify({'error': 'Message blocked by content policy. Repeated violations may result in account suspension.'}), 400

    conversation = Conversation.query.filter_by(
        id=conversation_id,
        user_id=user_id
    ).first()

    if not conversation:
        return jsonify({
            'error': 'Not found',
            'message': 'Conversation not found'
        }), 404

    subscription, err = _ensure_subscription(user_id)
    if err:
        return err

    credit_err = _check_credits(subscription)
    if credit_err:
        return credit_err

    tier_name = subscription.tier.name if subscription.tier else 'free'
    prefs = UserPreferences.query.filter_by(user_id=user_id).first()
    preferred_provider = prefs.preferred_model_provider if prefs else None
    model_config = resolve_model_with_preference(tier_name, preferred_provider)

    message = content

    # Query history BEFORE adding the new message to avoid autoflush bug
    conversation_history = _get_conversation_history(user_id, conversation_id)

    user_message = ChatMessage(
        user_id=user_id,
        conversation_id=conversation_id,
        role='user',
        content=message
    )
    db.session.add(user_message)
    db.session.commit()

    preferences_context = prefs.get_context_for_prompt() if prefs else None
    sandbox_active = False
    if prefs and prefs.learning_mode:
        try:
            from app import LEARNING_MODE_CONTEXT, SANDBOX_MODE_ADDENDUM
            preferences_context = (preferences_context or '') + '\n\n' + LEARNING_MODE_CONTEXT
            if prefs.sandbox_mode:
                preferences_context += '\n' + SANDBOX_MODE_ADDENDUM
                sandbox_active = True
        except ImportError:
            pass

    try:
        from services.memory_service import get_context_for_conversation
        from models import db
        memory_ctx = get_context_for_conversation(db, user_id, message)
        if memory_ctx:
            preferences_context = (preferences_context or '') + '\n\n' + memory_ctx
    except Exception:
        pass

    agent = current_app.config.get('DEVOPS_AGENT')

    # Build trial context for free-tier users
    trial_context = None
    if tier_name == 'free':
        credits_left = subscription.credits_remaining
        trial_context = (
            f"TRIAL CONTEXT: This user is on a free trial with {credits_left} credits remaining out of 20. "
            "They are experiencing the full DevOps agent with real tool execution. "
        )
        if credits_left <= 5:
            trial_context += (
                "Their credits are running low. Naturally weave in a brief mention that they can "
                "upgrade to the Starter plan ($29/month) for 500 credits/month to keep using these tools. "
                "Do NOT make this the focus -- still answer their question fully first."
            )

    try:
        response, actual_mc = _process_message(
            agent, message, conversation_history, preferences_context, user_id, model_config,
            trial_context=trial_context, sandbox_mode=sandbox_active
        )
        success = True
        error_msg = None
        # Deduct credit only after successful AI response
        subscription.use_credit()
    except Exception as e:
        response = f"Error processing request: {str(e)}"
        actual_mc = model_config
        success = False
        error_msg = str(e)

    is_first = conversation.title == 'New Chat'

    from services.chat_service import ensure_non_empty_response
    assistant_message = ChatMessage(
        user_id=user_id,
        conversation_id=conversation_id,
        role='assistant',
        content=ensure_non_empty_response(response)
    )
    db.session.add(assistant_message)

    usage_log = UsageLog(
        user_id=user_id,
        conversation_id=conversation_id,
        action_type='agent_message',
        credits_used=1 if success else 0,
        success=success,
        error_message=error_msg,
        ai_model=actual_mc.model
    )
    db.session.add(usage_log)

    if is_first:
        title = message.strip()
        if len(title) > 50:
            title = title[:47] + '...'
        conversation.title = title

    conversation.updated_at = datetime.utcnow()
    db.session.commit()

    return jsonify({
        'user_message': user_message.to_dict(),
        'assistant_message': assistant_message.to_dict(),
        'credits_remaining': subscription.credits_remaining,
        'model_info': {
            'provider': actual_mc.provider,
            'model': actual_mc.model,
            'display_name': actual_mc.display_name,
            'supports_tools': actual_mc.supports_tools,
        }
    }), 201


