#!/usr/bin/env python3
"""Regenerate config/tool_capabilities.yaml from safety.py's legacy classification.

Phase 1 of the governance refactor ships every medium/high-risk tool with a
declared capability so risk stops living in a hand-maintained name-set. This
script seeds that file by walking the whole tool catalogue and mapping each
tool's *legacy* risk level to a permission:

    legacy 'high'   -> permission: destroy
    legacy 'medium' -> permission: modify
    legacy 'low'    -> omitted (the resolver returns None, caller keeps 'low')

Run it once to (re)generate the file, then hand-tune entries in the YAML (a
create that is really 'modify', a genuinely irreversible delete, etc.). Inline
``capability=`` blocks in a module's ``get_tools()`` always win over this file,
so migrating a module later just means deleting its rows here.

Usage:
    python scripts/gen_tool_capabilities.py            # write config/tool_capabilities.yaml
    python scripts/gen_tool_capabilities.py --check    # exit 1 if the file is stale
"""
from __future__ import annotations

import argparse
import importlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.agent.safety import SafetyValidator  # noqa: E402

YAML_PATH = REPO_ROOT / "config" / "tool_capabilities.yaml"

TOOL_MODULES = (
    "command_tools", "aws_tools", "azure_tools", "gcp_tools", "kubernetes_tools",
    "git_tools", "github_tools", "docker_tools", "cicd_tools", "terraform_tools",
    "monitoring_tools", "ansible_tools", "alerting_tools", "pentest_tools",
    "sonarqube_tools", "nexus_tools", "devops_operations_tools", "verification_tools",
)

# validate_tool_call short-circuits before the capability layer for these, so a
# YAML entry would be dead weight. Keep in sync with tests/test_tool_capabilities.py.
ACTION_AWARE = {"manage_ec2_instance", "manage_vm", "manage_compute_instance"}
PENTEST_TOOLS = {
    "nmap_port_scan", "nmap_service_detection", "nikto_web_scan", "ssl_scan",
    "sqlmap_scan", "xss_scan", "zap_spider_scan", "quick_vulnerability_scan",
    "aws_security_audit", "azure_security_audit", "gcp_security_audit",
    "kubernetes_security_audit",
}
EXCLUDE = ACTION_AWARE | PENTEST_TOOLS

# Legacy 'high' tools that read/disclose rather than mutate — the Phase 5
# rollback stack should not treat them as reversible operations.
NON_MUTATING_HIGH = {
    "get_secret_value", "generate_s3_presigned_url",
    "git_grep_search", "get_diff", "git_diff_stat",
    "git_show_file_at_commit", "git_show_commit", "git_blame_file",
    "ansible_vault_view", "ansible_vault_decrypt",
    "terraform_output", "terraform_state_show",
}

_MUTATING_PREFIXES = (
    "delete_", "terminate_", "destroy_", "remove_", "drop_", "purge_", "create_",
    "update_", "modify_", "put_", "set_", "attach_", "detach_", "add_", "revoke_",
    "authorize_", "scale_", "resize_", "restart_", "reboot_", "start_", "stop_",
    "deploy_", "apply_", "rollback_", "trigger_", "run_", "register_", "deregister_",
    "associate_", "disassociate_", "enable_", "disable_", "publish_", "subscribe_",
    "cordon_", "uncordon_", "taint_", "drain_", "label_", "release_", "docker_",
    "git_", "terraform_", "nexus_", "helm_", "ansible_",
)


def _all_tool_names() -> set[str]:
    names: set[str] = set()
    for modname in TOOL_MODULES:
        mod = importlib.import_module(f"src.tools.{modname}")
        for tool in mod.get_tools():
            names.add(tool["name"])
    return names


def _mutating(name: str, permission: str) -> bool:
    if name in NON_MUTATING_HIGH:
        return False
    if permission in ("modify", "deploy", "destroy"):
        return True
    return name.startswith(_MUTATING_PREFIXES)


def build_yaml() -> str:
    sv = SafetyValidator()
    rows: list[tuple[str, str, bool]] = []
    for name in sorted(_all_tool_names()):
        if name in EXCLUDE:
            continue
        legacy = sv.legacy_risk_level(name)
        if legacy == "high":
            perm = "destroy"
        elif legacy == "medium":
            perm = "modify"
        else:
            continue
        rows.append((name, perm, _mutating(name, perm)))

    lines = [
        "# GENERATED by scripts/gen_tool_capabilities.py — do not edit rows by hand for",
        "# bulk changes; re-run the generator. Hand-tuning individual entries (a create",
        "# that is really 'modify', a genuinely irreversible delete) is expected and",
        "# survives regeneration only if you also teach the generator. Inline",
        "# capability= blocks in a module's get_tools() override every row here.",
        "#",
        "# permission: read | analyze | modify | deploy | destroy",
        "# See src/agent/tool_capabilities.py and docs/governance-refactor.md.",
        "",
        "tools:",
    ]
    for name, perm, mut in rows:
        lines.append(f"  {name}: {{ permission: {perm}, mutating: {str(mut).lower()} }}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args()

    generated = build_yaml()
    if args.check:
        current = YAML_PATH.read_text(encoding="utf-8") if YAML_PATH.exists() else ""
        if current != generated:
            print("config/tool_capabilities.yaml is stale — run: python scripts/gen_tool_capabilities.py")
            return 1
        print("config/tool_capabilities.yaml is up to date")
        return 0

    YAML_PATH.write_text(generated, encoding="utf-8")
    n = generated.count("\n  ")
    print(f"wrote {YAML_PATH.relative_to(REPO_ROOT)} ({n} tools)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
