#!/usr/bin/env bash
#
# Run a SonarQube analysis of this repo against the local server defined in
# docker-compose.sonar.yml.
#
#   ./scripts/sonar-scan.sh              # scan (reuses existing coverage.xml)
#   ./scripts/sonar-scan.sh --coverage   # run pytest first to refresh coverage.xml
#
# On first run this rotates SonarQube's default admin password to a freshly
# generated one and mints an analysis token, storing both in .sonar-token
# (gitignored). Later runs reuse that file.

set -euo pipefail

cd "$(dirname "$0")/.."

COMPOSE_FILE="docker-compose.sonar.yml"
CRED_FILE=".sonar-token"
HOST_URL="http://localhost:9000"
READY_TIMEOUT=300

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
fail() { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# --- Preflight ---------------------------------------------------------------
command -v docker >/dev/null 2>&1 || fail "docker not found on PATH"
docker info >/dev/null 2>&1 || fail "Docker daemon is not running (start Docker Desktop)"

# SonarQube's embedded Elasticsearch refuses to boot below this and the failure
# surfaces as an opaque container exit, so check it explicitly.
MMC=$(docker run --rm --privileged alpine sysctl -n vm.max_map_count 2>/dev/null || echo 0)
if [ "$MMC" -lt 262144 ]; then
  fail "vm.max_map_count is $MMC, needs >= 262144.
  Fix (Docker Desktop / WSL2):  wsl -d docker-desktop sysctl -w vm.max_map_count=262144"
fi

# --- Optional coverage refresh ----------------------------------------------
if [ "${1:-}" = "--coverage" ]; then
  log "Running pytest with coverage to refresh coverage.xml"
  python -m pytest -q --cov=. --cov-report=xml:coverage.xml \
    --cov-config=.coveragerc || log "pytest reported failures; continuing with the coverage that was produced"
fi

# --- Normalise coverage paths for the scanner container ----------------------
# coverage.py records an absolute <source> path from the machine that ran the
# tests. The scanner runs in Linux with the repo bind-mounted at /usr/src, so a
# Windows path (or any host path) makes it log
#   WARN Invalid directory path in 'source' element: C:/Users/...
# and silently import 0% coverage. Rewriting the element is safe: coverage.xml
# is gitignored and regenerated on every --coverage run. CI does not need this,
# because there the tests and the scan share one filesystem.
if [ -f coverage.xml ] && ! grep -q '<source>/usr/src</source>' coverage.xml; then
  log "Rewriting coverage.xml <source> to /usr/src for the scanner container"
  sed -i 's|<source>.*</source>|<source>/usr/src</source>|' coverage.xml
fi

# --- Start the server --------------------------------------------------------
log "Starting SonarQube stack"
docker compose -f "$COMPOSE_FILE" up -d sonar-db sonarqube

log "Waiting for SonarQube to report UP (up to ${READY_TIMEOUT}s; first boot is slow)"
deadline=$(( $(date +%s) + READY_TIMEOUT ))
until curl -sf "$HOST_URL/api/system/status" 2>/dev/null | grep -q '"status":"UP"'; do
  [ "$(date +%s)" -lt "$deadline" ] || fail "SonarQube did not come up within ${READY_TIMEOUT}s.
  Check logs:  docker compose -f $COMPOSE_FILE logs sonarqube"
  sleep 5
  printf '.'
done
printf '\n'
log "SonarQube is UP at $HOST_URL"

# --- Credentials -------------------------------------------------------------
if [ -f "$CRED_FILE" ]; then
  # shellcheck disable=SC1090
  . "$CRED_FILE"
  log "Reusing analysis token from $CRED_FILE"
else
  log "First run: rotating the default admin password and minting an analysis token"

  # SonarQube requires a strong password; build one that always satisfies the
  # policy rather than shipping a hardcoded credential in this script. The
  # prefix is not a secret - it only guarantees one upper, one lower, one digit
  # and one symbol are present whatever /dev/urandom produces.
  POLICY_PREFIX="$(printf 'Sq1\41')"
  RANDOM_PART=$(head -c 32 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 20)
  SONAR_ADMIN_PASSWORD="${POLICY_PREFIX}${RANDOM_PART}"

  curl -sf -u admin:admin -X POST "$HOST_URL/api/users/change_password" \
    -d "login=admin" \
    -d "previousPassword=admin" \
    -d "password=${SONAR_ADMIN_PASSWORD}" >/dev/null \
    || fail "Could not rotate the admin password. If this server was set up before,
  delete $CRED_FILE is not enough - reset with:
    docker compose -f $COMPOSE_FILE down -v   (destroys all analysis history)"

  SONAR_TOKEN=$(curl -sf -u "admin:${SONAR_ADMIN_PASSWORD}" -X POST \
    "$HOST_URL/api/user_tokens/generate" \
    -d "name=devops-agent-scanner-$(date +%s)" \
    | sed -n 's/.*"token":"\([^"]*\)".*/\1/p')

  [ -n "$SONAR_TOKEN" ] || fail "Token generation returned no token"

  umask 077
  cat > "$CRED_FILE" <<EOF
# Generated by scripts/sonar-scan.sh - DO NOT COMMIT (gitignored).
# Sign in to $HOST_URL as admin with SONAR_ADMIN_PASSWORD below.
SONAR_ADMIN_PASSWORD='${SONAR_ADMIN_PASSWORD}'
SONAR_TOKEN='${SONAR_TOKEN}'
EOF
  log "Credentials written to $CRED_FILE (mode 600, gitignored)"
fi

# --- Scan --------------------------------------------------------------------
log "Running sonar-scanner"
SONAR_TOKEN="$SONAR_TOKEN" docker compose -f "$COMPOSE_FILE" --profile scan \
  run --rm sonar-scanner

log "Analysis submitted. Dashboard: $HOST_URL/dashboard?id=devops-agent"
log "Sign in as admin - password is in $CRED_FILE"
