class InfrastructureSpec:
    """Specification for infrastructure to provision."""

    def __init__(self):
        self.resources: List[Dict] = []
        self.networking: Dict = {}
        self.security: Dict = {}
        self.monitoring: Dict = {}
        self.cloud_provider = 'aws'
        self.region = 'us-east-1'
        self.tags: Dict[str, str] = {}

    def add_resource(self, resource_type: str, config: Dict):
        """Add a resource to the specification."""
        self.resources.append({
            'type': resource_type,
            'config': config,
            'id': f"res_{secrets.token_hex(4)}"
        })

    def to_dict(self) -> Dict:
        return {
            'resources': self.resources,
            'networking': self.networking,
            'security': self.security,
            'monitoring': self.monitoring,
            'cloud_provider': self.cloud_provider,
            'region': self.region,
            'tags': self.tags
        }

    def to_terraform(self) -> str:
        """Convert the spec to Terraform HCL for AWS.

        No AMI id and no password is ever written in: EC2 looks up the newest
        Ubuntu 22.04 image from Canonical's own account at plan time, and RDS
        has AWS manage the master password in Secrets Manager.
        """
        lines = [
            '# Generated by DevOps Agent from a plain-English description.',
            '# Review it, then run terraform plan before applying anything.',
            '',
            'terraform {',
            '  required_providers {',
            '    aws = {',
            '      source = "hashicorp/aws"',
            '    }',
            '  }',
            '}',
            '',
            'provider "aws" {',
            f'  region = "{self.region}"',
            '}',
            '',
        ]

        if any(r['type'] == 'ec2' for r in self.resources):
            lines.extend([
                '# Newest Ubuntu 22.04 image, only from Canonical\'s own AWS account.',
                'data "aws_ami" "ubuntu" {',
                '  most_recent = true',
                f'  owners      = ["{UBUNTU_AMI_OWNER}"]',
                '',
                '  filter {',
                '    name   = "name"',
                f'    values = ["{UBUNTU_AMI_NAME}"]',
                '  }',
                '}',
                '',
            ])

        for resource in self.resources:
            lines.extend(self._resource_to_terraform(resource))
            lines.append('')

        return '\n'.join(lines)

    def _tags(self, name: str) -> List[str]:
        out = ['  tags = {', f'    Name = "{name}"']
        for key, value in self.tags.items():
            out.append(f'    {key} = "{value}"')
        out.append('  }')
        return out

    def _resource_to_terraform(self, resource: Dict) -> List[str]:
        """Convert a single resource to Terraform."""
        res_type = resource['type']
        config = resource['config']
        res_id = resource['id']
        name = config.get('name', res_id)

        if res_type == 'ec2':
            return [
                f'resource "aws_instance" "{res_id}" {{',
                '  ami           = data.aws_ami.ubuntu.id',
                f'  instance_type = "{config.get("instance_type", "t3.micro")}"',
                '',
                '  metadata_options {',
                '    http_tokens = "required"',
                '  }',
                '',
                *self._tags(name),
                '}',
            ]
        if res_type == 's3':
            return [
                f'resource "aws_s3_bucket" "{res_id}" {{',
                f'  bucket = "{config.get("bucket_name", res_id)}"',
                '',
                *self._tags(name),
                '}',
                '',
                f'resource "aws_s3_bucket_public_access_block" "{res_id}" {{',
                f'  bucket                  = aws_s3_bucket.{res_id}.id',
                '  block_public_acls       = true',
                '  block_public_policy     = true',
                '  ignore_public_acls      = true',
                '  restrict_public_buckets = true',
                '}',
            ]
        if res_type == 'rds':
            return [
                f'resource "aws_db_instance" "{res_id}" {{',
                f'  identifier                  = "{name}"',
                f'  engine                      = "{config.get("engine", "postgres")}"',
                f'  instance_class              = "{config.get("instance_class", "db.t3.micro")}"',
                f'  allocated_storage           = {config.get("storage", 20)}',
                '  username                    = "dbadmin"',
                '  manage_master_user_password = true',
                '  storage_encrypted           = true',
                '  publicly_accessible         = false',
                f'  multi_az                    = {"true" if config.get("multi_az") else "false"}',
                '  deletion_protection         = true',
                f'  final_snapshot_identifier   = "{name}-final"',
                '',
                *self._tags(name),
                '}',
            ]
        if res_type == 'vpc':
            return [
                f'resource "aws_vpc" "{res_id}" {{',
                f'  cidr_block           = "{config.get("cidr_block", "10.0.0.0/16")}"',
                '  enable_dns_support   = true',
                '  enable_dns_hostnames = true',
                '',
                *self._tags(name),
                '}',
            ]
        if res_type == 'alb':
            return [
                f'# Load balancer "{name}": not generated here, because it needs your',
                '# subnets and security groups. Ask in Chat to build one in your account.',
            ]
        return [f'# Resource type {res_type} is not supported here yet.']


