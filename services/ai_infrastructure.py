def _get_or_create_system_user():
    """Owner for public starter templates (user_id is NOT NULL on the model).

    Only ever called from inside seed_public_templates()'s seed_lock() block.
    Must NOT commit: the Postgres advisory lock seed_lock() takes is
    transaction-scoped (pg_advisory_xact_lock), so a commit here would release
    it before the template rows are inserted, reopening the exact concurrent
    double-seed race the lock exists to close. flush() instead, so `user.id`
    is populated and visible within the same still-open transaction; the
    caller's seed_lock() commits everything together at the end.
    """
    from models import db, User
    user = User.query.filter_by(email=SYSTEM_TEMPLATE_OWNER_EMAIL).first()
    if user:
        return user
    user = User(
        email=SYSTEM_TEMPLATE_OWNER_EMAIL,
        username='system',
        full_name='DevOps Agent',
        role='viewer',
    )
    # Unusable password — this account can never log in.
    user.set_password(secrets.token_urlsafe(32))
    if hasattr(user, 'email_verified'):
        user.email_verified = True
    db.session.add(user)
    db.session.flush()
    return user


# Arbitrary but fixed — must not collide with starter_workflows' key.
_SEED_LOCK_KEY = 0x49_4E_46_52  # "INFR"


def seed_public_templates() -> int:
    """Idempotently seed the curated public starter templates.

    Safe to call on every startup: existing public templates (matched by name)
    are skipped, so it never duplicates. Returns the number of templates added.
    """
    from models import db, InfrastructureTemplate
    from services.starter_templates import STARTER_TEMPLATES
    from services.seed_lock import seed_lock

    # Under the lock because every gunicorn worker seeds at import simultaneously —
    # an unguarded check-then-insert lets each one insert the whole catalog.
    with seed_lock(_SEED_LOCK_KEY):
        existing_names = {
            t.name for t in InfrastructureTemplate.query.filter_by(is_public=True).all()
        }
        to_add = [tpl for tpl in STARTER_TEMPLATES if tpl['name'] not in existing_names]
        if to_add:
            owner = _get_or_create_system_user()
            for tpl in to_add:
                db.session.add(InfrastructureTemplate(
                    user_id=owner.id,
                    name=tpl['name'],
                    description=tpl['description'],
                    category=tpl['category'],
                    cloud_provider=tpl['cloud_provider'],
                    template_type=tpl['template_type'],
                    template_content=tpl['template_content'],
                    variables=tpl['variables'],
                    estimated_monthly_cost=tpl['estimated_monthly_cost'],
                    is_public=True,
                ))

    if to_add:
        logger.info(f"Seeded {len(to_add)} public infrastructure template(s)")
    return len(to_add)
