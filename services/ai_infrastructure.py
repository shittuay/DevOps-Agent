class InfrastructureSpec:
    """Specification for infrastructure to provision."""

    def __init__(self):
        self.resources: List[Dict] = []
        self.networking: Dict = {}
        self.security: Dict = {}
        self.monitoring: Dict = {}
        self.estimated_cost: float = 0.0
        self.cloud_provider = 'aws'
        self.region = 'us-east-1'
        self.tags: Dict[str, str] = {}

    def add_resource(self, resource_type: str, config: Dict):
        """Add a resource to the specification."""
        self.resources.append({
            'type': resource_type,
            'config': config,
            'id': f"res_{secrets.token_hex(4)}"
        })

    def to_dict(self) -> Dict:
        return {
            'resources': self.resources,
            'networking': self.networking,
            'security': self.security,
            'monitoring': self.monitoring,
            'estimated_cost': self.estimated_cost,
            'cloud_provider': self.cloud_provider,
            'region': self.region,
            'tags': self.tags
        }

    def to_terraform(self) -> str:
        """Convert spec to Terraform HCL."""
        lines = [
            f'# Generated by DevOps Agent AI',
            f'# Cloud Provider: {self.cloud_provider}',
            f'# Region: {self.region}',
            f'# Estimated Monthly Cost: ${self.estimated_cost:.2f}',
            '',
            'terraform {',
            '  required_providers {',
            f'    {self.cloud_provider} = {{',
            f'      source = "hashicorp/{self.cloud_provider}"',
            '    }',
            '  }',
            '}',
            '',
            f'provider "{self.cloud_provider}" {{',
            f'  region = "{self.region}"',
            '}',
            ''
        ]

        for resource in self.resources:
            lines.extend(self._resource_to_terraform(resource))
            lines.append('')

        return '\n'.join(lines)

    def _resource_to_terraform(self, resource: Dict) -> List[str]:
        """Convert a single resource to Terraform."""
        res_type = resource['type']
        config = resource['config']
        res_id = resource['id']

        if res_type == 'ec2':
            return [
                f'resource "aws_instance" "{res_id}" {{',
                f'  ami           = "{config.get("ami", "ami-0c55b159cbfafe1f0")}"',
                f'  instance_type = "{config.get("instance_type", "t3.micro")}"',
                '',
                '  tags = {',
                f'    Name = "{config.get("name", res_id)}"',
                '  }',
                '}'
            ]
        elif res_type == 's3':
            return [
                f'resource "aws_s3_bucket" "{res_id}" {{',
                f'  bucket = "{config.get("bucket_name", res_id)}"',
                '',
                '  tags = {',
                f'    Name = "{config.get("name", res_id)}"',
                '  }',
                '}'
            ]
        elif res_type == 'rds':
            return [
                f'resource "aws_db_instance" "{res_id}" {{',
                f'  identifier           = "{config.get("name", res_id)}"',
                f'  engine               = "{config.get("engine", "postgres")}"',
                f'  engine_version       = "{config.get("engine_version", "14")}"',
                f'  instance_class       = "{config.get("instance_class", "db.t3.micro")}"',
                f'  allocated_storage    = {config.get("storage", 20)}',
                f'  storage_encrypted    = true',
                '',
                '  tags = {',
                f'    Name = "{config.get("name", res_id)}"',
                '  }',
                '}'
            ]

        return [f'# Resource type {res_type} not yet supported']


class AIInfrastructureService:
    """AI-powered infrastructure service with database persistence."""

    def __init__(self, user_id: Optional[int] = None):
        self.user_id = user_id
        self._init_patterns()

    def _get_db(self):
        """Get database session."""
        from models import db
        return db

    def _get_request_model(self):
        """Get ProvisioningRequestModel."""
        from models import ProvisioningRequestModel
        return ProvisioningRequestModel

    def _get_template_model(self):
        """Get InfrastructureTemplate."""
        from models import InfrastructureTemplate
        return InfrastructureTemplate

    def _init_patterns(self):
        """Initialize natural language patterns."""
        self.intent_patterns = {
            'create_server': [
                r'create\s+(?:a\s+)?(?:web\s+)?server',
                r'spin\s+up\s+(?:an?\s+)?(?:ec2\s+)?instance',
                r'launch\s+(?:a\s+)?(?:new\s+)?server',
                r'provision\s+(?:a\s+)?(?:virtual\s+)?machine',
                r'deploy\s+(?:a\s+)?server',
            ],
            'create_database': [
                r'create\s+(?:a\s+)?database',
                r'set\s+up\s+(?:a\s+)?(?:rds|mysql|postgres)',
                r'provision\s+(?:a\s+)?db',
                r'deploy\s+(?:a\s+)?database',
            ],
            'create_storage': [
                r'create\s+(?:a\s+)?(?:s3\s+)?bucket',
                r'set\s+up\s+(?:object\s+)?storage',
                r'provision\s+storage',
            ],
            'create_load_balancer': [
                r'create\s+(?:a\s+)?load\s*balancer',
                r'set\s+up\s+(?:an?\s+)?(?:elb|alb)',
                r'add\s+(?:a\s+)?load\s*balancer',
            ],
            'create_vpc': [
                r'create\s+(?:a\s+)?vpc',
                r'set\s+up\s+(?:a\s+)?network',
                r'provision\s+(?:a\s+)?virtual\s+network',
            ],
            'scale_up': [
                r'scale\s+up',
                r'increase\s+(?:the\s+)?capacity',
                r'add\s+more\s+(?:servers|instances)',
            ],
            'scale_down': [
                r'scale\s+down',
                r'reduce\s+(?:the\s+)?capacity',
                r'remove\s+(?:some\s+)?(?:servers|instances)',
            ],
        }

        self.size_patterns = {
            'small': [r'small', r'micro', r'minimal', r'basic', r't2\.micro', r't3\.micro'],
            'medium': [r'medium', r'standard', r't2\.small', r't3\.small', r't3\.medium'],
            'large': [r'large', r'big', r'powerful', r't2\.large', r't3\.large', r'm5\.large'],
            'xlarge': [r'extra\s*large', r'xlarge', r'high\s*performance', r'c5', r'r5'],
        }

        self.region_patterns = {
            'us-east-1': [r'us\s*east', r'virginia', r'n\.?\s*virginia'],
            'us-west-2': [r'us\s*west', r'oregon'],
            'eu-west-1': [r'eu\s*west', r'ireland', r'europe'],
            'ap-southeast-1': [r'asia', r'singapore', r'ap\s*southeast'],
        }

    # Natural Language Processing

    def parse_request(self, text: str) -> Dict:
        """Parse natural language request into structured intent."""
        text_lower = text.lower()
        intent = {
            'action': None,
            'resource_type': None,
            'size': 'medium',
            'region': 'us-east-1',
            'count': 1,
            'name': None,
            'features': [],
            'raw_text': text
        }

        for action, patterns in self.intent_patterns.items():
            for pattern in patterns:
                if re.search(pattern, text_lower):
                    intent['action'] = action
                    break
            if intent['action']:
                break

        for size, patterns in self.size_patterns.items():
            for pattern in patterns:
                if re.search(pattern, text_lower):
                    intent['size'] = size
                    break

        for region, patterns in self.region_patterns.items():
            for pattern in patterns:
                if re.search(pattern, text_lower):
                    intent['region'] = region
                    break

        count_match = re.search(r'(\d+)\s*(?:servers|instances|databases)', text_lower)
        if count_match:
            intent['count'] = int(count_match.group(1))

        name_match = re.search(r'(?:named?|called?)\s+["\']?(\w+)["\']?', text_lower)
        if name_match:
            intent['name'] = name_match.group(1)

        if 'high availability' in text_lower or 'ha' in text_lower:
            intent['features'].append('high_availability')
        if 'encrypted' in text_lower or 'encryption' in text_lower:
            intent['features'].append('encryption')
        if 'public' in text_lower:
            intent['features'].append('public_access')
        if 'private' in text_lower:
            intent['features'].append('private')
        if 'backup' in text_lower:
            intent['features'].append('backup')

        return intent

    def generate_spec(self, intent: Dict) -> InfrastructureSpec:
        """Generate infrastructure specification from parsed intent."""
        spec = InfrastructureSpec()
        spec.region = intent.get('region', 'us-east-1')
        spec.tags = {'ManagedBy': 'DevOpsAgent', 'Environment': 'production'}

        action = intent.get('action', '')
        size = intent.get('size', 'medium')
        count = intent.get('count', 1)
        name = intent.get('name', 'devops-agent-resource')

        instance_sizes = {
            'small': ('t3.micro', 5.0),
            'medium': ('t3.small', 15.0),
            'large': ('t3.medium', 30.0),
            'xlarge': ('t3.large', 60.0),
        }

        db_sizes = {
            'small': ('db.t3.micro', 15.0),
            'medium': ('db.t3.small', 25.0),
            'large': ('db.t3.medium', 50.0),
            'xlarge': ('db.t3.large', 100.0),
        }

        if action == 'create_server':
            instance_type, cost = instance_sizes.get(size, ('t3.small', 15.0))
            for i in range(count):
                spec.add_resource('ec2', {
                    'name': f"{name}-{i+1}" if count > 1 else name,
                    'instance_type': instance_type,
                    'ami': 'ami-0c55b159cbfafe1f0'
                })
            spec.estimated_cost = cost * count

        elif action == 'create_database':
            instance_class, cost = db_sizes.get(size, ('db.t3.small', 25.0))
            spec.add_resource('rds', {
                'name': name,
                'engine': 'postgres',
                'engine_version': '14',
                'instance_class': instance_class,
                'storage': 20 if size in ['small', 'medium'] else 100,
                'multi_az': 'high_availability' in intent.get('features', [])
            })
            spec.estimated_cost = cost

        elif action == 'create_storage':
            spec.add_resource('s3', {
                'bucket_name': f"{name}-{secrets.token_hex(4)}",
                'name': name,
                'encryption': 'encryption' in intent.get('features', [])
            })
            spec.estimated_cost = 5.0

        elif action == 'create_load_balancer':
            spec.add_resource('alb', {
                'name': name,
                'internal': 'private' in intent.get('features', [])
            })
            spec.estimated_cost = 25.0

        elif action == 'create_vpc':
            spec.add_resource('vpc', {
                'name': name,
                'cidr_block': '10.0.0.0/16'
            })
            spec.estimated_cost = 0.0

        return spec

    # Request Processing

    def create_request(self, user_id: int, request_text: str) -> Any:
        """Create a new provisioning request."""
        ProvisioningRequestModel = self._get_request_model()
        db = self._get_db()

        parsed_intent = self.parse_request(request_text)

        request = ProvisioningRequestModel(
            user_id=user_id,
            request_text=request_text,
            status='planning',
            parsed_intent=parsed_intent
        )

        if parsed_intent.get('action'):
            spec = self.generate_spec(parsed_intent)
            request.generated_spec = spec.to_dict()
            request.terraform_code = spec.to_terraform()
            request.estimated_cost = spec.estimated_cost
            request.status = 'reviewing'
            request.review_notes = [
                f"Detected intent: {parsed_intent['action']}",
                f"Estimated monthly cost: ${spec.estimated_cost:.2f}",
                f"Resources to create: {len(spec.resources)}"
            ]
        else:
            request.status = 'failed'
            request.error_message = "Could not understand the request. Please be more specific."

        db.session.add(request)
        db.session.commit()

        logger.info(f"Created provisioning request: {request.id}")
        return request

    def get_request(self, request_id: int) -> Optional[Any]:
        """Get a provisioning request (scoped to self.user_id when set)."""
        ProvisioningRequestModel = self._get_request_model()
        query = ProvisioningRequestModel.query.filter_by(id=request_id)
        if self.user_id is not None:
            query = query.filter_by(user_id=self.user_id)
        return query.first()

    def get_user_requests(self, user_id: int) -> List[Any]:
        """Get all requests for a user."""
        ProvisioningRequestModel = self._get_request_model()
        return ProvisioningRequestModel.query.filter_by(user_id=user_id)\
            .order_by(ProvisioningRequestModel.created_at.desc()).all()

    def approve_request(self, request_id: int, user_id: int) -> bool:
        """Approve a provisioning request."""
        db = self._get_db()
        request = self.get_request(request_id)
        if not request or request.status != 'reviewing':
            return False

        request.status = 'approved'
        request.approved_by = user_id
        request.approved_at = utcnow()
        db.session.commit()
        return True

    def execute_request(self, request_id: int) -> bool:
        """Execute an approved provisioning request."""
        db = self._get_db()
        request = self.get_request(request_id)
        if not request or request.status != 'approved':
            return False

        request.status = 'provisioning'

        spec = request.generated_spec or {}
        execution_log = []
        for resource in spec.get('resources', []):
            execution_log.append({
                'timestamp': utcnow().isoformat(),
                'action': 'creating',
                'resource': resource['type'],
                'resource_id': resource['id']
            })

        execution_log.append({
            'timestamp': utcnow().isoformat(),
            'action': 'completed',
            'message': 'All resources provisioned successfully'
        })

        request.execution_log = execution_log
        request.status = 'completed'
        request.completed_at = utcnow()
        db.session.commit()

        return True

    def cancel_request(self, request_id: int) -> bool:
        """Cancel a provisioning request."""
        db = self._get_db()
        request = self.get_request(request_id)
        if not request or request.status in ['completed', 'cancelled']:
            return False

        request.status = 'cancelled'
        db.session.commit()
        return True

    # Template Management

    @staticmethod
    def template_to_dict(t: Any) -> Dict[str, Any]:
        """Canonical, JSON-safe shape for an InfrastructureTemplate.

        This is the single source of truth for template field names — the API,
        the templates grid, and the detail page all consume this shape, so model
        column names (cloud_provider, estimated_monthly_cost) never leak into
        templates as mismatched attributes.
        """
        variables = t.variables if isinstance(t.variables, list) else []
        return {
            'id': t.id,
            'name': t.name,
            'description': t.description,
            'category': t.category,
            'cloud_provider': t.cloud_provider,
            'template_type': t.template_type,
            'template_content': t.template_content or '',
            'variables': variables,
            'estimated_cost': t.estimated_monthly_cost or 0,
            'is_public': bool(t.is_public),
            'use_count': t.use_count or 0,
        }

